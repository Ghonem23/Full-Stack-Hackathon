"""## 6. Retrieval — with the hallucination guard

This is the **first line of defense** against hallucination: if the top retrieved chunk isn't actually similar enough to the question, we don't hand anything to the LLM to "make sense of" — we short-circuit straight to "I don't know.
"""

def retrieve(query, top_k=TOP_K, similarity_threshold=SIMILARITY_THRESHOLD):
    query_embedding = embed_texts([query])[0].tolist()
    results = collection.query(query_embeddings=[query_embedding], n_results=top_k)

    retrieved = []
    chunks_by_id = {c["chunk_id"]: c for c in all_chunks}
    for chunk_id, distance in zip(results["ids"][0], results["distances"][0]):
        similarity = 1 - distance  # Chroma بيرجع cosine distance، مش similarity
        if similarity >= similarity_threshold:
            chunk = dict(chunks_by_id[chunk_id])
            chunk["similarity"] = similarity
            retrieved.append(chunk)
    return retrieved

