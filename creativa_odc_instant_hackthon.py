def bm25_search(query, top_k=10):
    scores = bm25.get_scores(query.lower().split())
    ranked_idx = scores.argsort()[::-1][:top_k]
    return [(primary_chunks[i], float(scores[i])) for i in ranked_idx]


def minmax_normalize(values):
    lo, hi = min(values), max(values)
    if hi - lo < 1e-9:
        return [0.0 for _ in values]
    return [(v - lo) / (hi - lo) for v in values]


def hybrid_search(query, top_k=10, alpha=HYBRID_ALPHA):
    semantic_hits = retrieve_from_config(query, PRIMARY_CONFIG, top_k=top_k, similarity_threshold=0.0)
    keyword_hits = bm25_search(query, top_k=top_k)

    sem_scores = {c["chunk_id"]: c["similarity"] for c in semantic_hits}
    kw_scores = {c["chunk_id"]: s for c, s in keyword_hits}

    all_ids = set(sem_scores) | set(kw_scores)
    sem_norm = dict(zip(sem_scores, minmax_normalize(list(sem_scores.values())))) if sem_scores else {}
    kw_norm = dict(zip(kw_scores, minmax_normalize(list(kw_scores.values())))) if kw_scores else {}

    by_id = {c["chunk_id"]: c for c in semantic_hits}
    by_id.update({c["chunk_id"]: c for c, _ in keyword_hits})

    blended = []
    for cid in all_ids:
        score = alpha * sem_norm.get(cid, 0.0) + (1 - alpha) * kw_norm.get(cid, 0.0)
        blended.append((by_id[cid], score))
    blended.sort(key=lambda x: -x[1])
    return blended[:top_k]


