"""## 27. Day 4 aggregate metrics table (Slide 14)

Precision@K (Section 16) is already aggregated across the eval set. The citation/faithfulness
metrics from Slide 14 were not — `validate_citation_coverage` only ever reported one answer at a
time. This runs `answer_query_v2` over every `EVAL_QUESTIONS` item and rolls the results up into
the same 5-row table the slide shows.

**Citation correctness is left as `manual`, not computed automatically here** — the automatic
check (citation *validity*) only confirms a cited `chunk_id` is real; whether it's the *right*
evidence for that specific claim needs a human, which is exactly what `manual_citation_check`
(9.5.7) is for. Reporting it as an automatic number would be a fake metric (Slide 4: "Do not
create fake metrics").
"""

def compute_day4_metrics(questions, top_k=TOP_K, similarity_threshold=SIMILARITY_THRESHOLD):
    n_citations_total = 0
    n_invalid_citations_total = 0
    n_claims_total = 0
    n_claims_cited = 0
    n_answers_scored = 0

    for q in questions:
        result = answer_query_v2(q, top_k=top_k, similarity_threshold=similarity_threshold, verbose=False)
        report = result["coverage_report"]
        if report is None:
            continue  # refusal / unsafe query -- nothing to score
        n_answers_scored += 1

        n_citations_total += report["n_citations"]
        n_invalid_citations_total += report["n_invalid_citations"]

        cited_claims = report["n_citations"]
        uncited_claims = report["n_uncited_long_sentences"]
        n_claims_total += cited_claims + uncited_claims
        n_claims_cited += cited_claims

        time.sleep(2)  # Groq rate limit

    n_valid_citations = n_citations_total - n_invalid_citations_total
    # proxy for "supported": a cited claim whose citation was valid
    n_claims_supported = max(n_claims_cited - n_invalid_citations_total, 0)

    def safe_div(a, b):
        return round(a / b, 3) if b else None

    rows = [
        {"Metric": "Citation validity", "Formula": "Valid citations / Total citations",
         "Value": safe_div(n_valid_citations, n_citations_total)},
        {"Metric": "Citation correctness", "Formula": "Correct supporting citations / Total citations checked",
         "Value": "manual - see 9.5.7 manual_citation_check"},
        {"Metric": "Citation coverage", "Formula": "Claims with a citation / Total claims",
         "Value": safe_div(n_claims_cited, n_claims_total)},
        {"Metric": "Claim faithfulness", "Formula": "Supported claims / Total claims",
         "Value": safe_div(n_claims_supported, n_claims_total)},
        {"Metric": "Unsupported claim rate (lower is better)", "Formula": "Unsupported claims / Total claims",
         "Value": safe_div(n_claims_total - n_claims_supported, n_claims_total)},
    ]
    print(f"Scored {n_answers_scored}/{len(questions)} answers (refusals excluded from claim/citation metrics).\n")
    return pd.DataFrame(rows)


