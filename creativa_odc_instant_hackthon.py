def build_context_block(retrieved_chunks):
    """Turns retrieved chunks into a numbered context block the LLM can cite from."""
    blocks = []
    for i, c in enumerate(retrieved_chunks, start=1):
        blocks.append(
            f"[{i}] source={c['source']} | page={c['page']} | section={c.get('section', 'n/a')} | "
            f"similarity={c['similarity']:.3f}\n{c['text']}"
        )
    return "\n\n".join(blocks)

import time

def _wait_for_groq_retry(response, attempt, base_wait=5, max_wait=60):
    retry_after = response.headers.get("retry-after") or response.headers.get("Retry-After")
    if retry_after is not None:
        try:
            wait_time = float(retry_after) + 1
        except ValueError:
            wait_time = min(base_wait * (attempt + 1), max_wait)
    else:
        wait_time = min(base_wait * (attempt + 1), max_wait)
    print(f"Rate limited. Waiting {wait_time:.0f}s before retry {attempt+1} "
          f"(server-specified: {retry_after is not None})...")
    time.sleep(wait_time)


def generate_answer(query, retrieved_chunks, max_retries=8):
    context_block = build_context_block(retrieved_chunks)
    user_message = (
        f"CONTEXT:\n{context_block}\n\n"
        f"QUESTION: {query}\n\n"
        f"Answer using only the CONTEXT above. Cite every claim as [source, page]."
    )

    approx_tokens = len(context_block) // 4
    if approx_tokens > 3000:
        print(f"[warning] Context is ~{approx_tokens} tokens — consider lowering TOP_K.")

    for attempt in range(max_retries):
        response = requests.post(
            "https://api.groq.com/openai/v1/chat/completions",
            headers={"Authorization": f"Bearer {GROQ_API_KEY}"},
            json={
                "model": GROQ_MODEL,
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": user_message},
                ],
                "temperature": 0.2,
            },
            timeout=60,
        )
        if response.status_code == 200:
            return response.json()["choices"][0]["message"]["content"]
        if response.status_code == 429:
            _wait_for_groq_retry(response, attempt)
            continue
        print("Groq error:", response.status_code, response.text)
        response.raise_for_status()
    raise RuntimeError(f"Failed after {max_retries} retries due to rate limiting.")

"""## 8. Full pipeline

Combines retrieval + the similarity gate + generation into one function. This is the function you actually call.
"""

def answer_query(query, top_k=TOP_K, similarity_threshold=SIMILARITY_THRESHOLD, verbose=True):
    retrieved = retrieve(query, top_k=top_k, similarity_threshold=similarity_threshold)

    if not retrieved:
        if verbose:
            print("[retrieval gate] No chunk cleared the similarity threshold — refusing without calling the LLM.\n")
        return {
            "query": query,
            "answer": REFUSAL_TEXT,
            "citations": [],
            "retrieved_chunks": [],
        }

    answer_text = generate_answer(query, retrieved)
    citations = sorted({f"{c['source']}, page {c['page']}" for c in retrieved})

    return {
        "query": query,
        "answer": answer_text,
        "citations": citations,
        "retrieved_chunks": retrieved,
    }


def print_result(result):
    print(f"Q: {result['query']}\n")
